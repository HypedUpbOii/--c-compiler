// arithematic expressions with nested braces

void main() {
    int a;
    int b;
    int c;
    int d;
    int e;
    int f;
    int o;

    a = 24;
    b = 36;
    c = 40;
    d = (a + b + c) / 10;
    e = (3 * (c * 5)) + (d * 30);
    f = (e - d) / ((2 * c) + (b / (c / d)));
    o = (f / d) + (e - f) + (c / d);
}